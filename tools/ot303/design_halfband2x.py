# OT-303 Phase 2b (lean engine): shorter 2x -> 1x half-band candidates for the second decimator stage.
#   uv run --with scipy --with numpy python3 tools/ot303/design_halfband2x.py
# Half-band trick: an even-length (type II) one-band remez design g of length K over [0, 2 fp / fs]
# gives the half-band's odd taps (g / 2) around a centre of 0.5; length N = 2K - 1, K MACs per
# output (the centre is a shift). Writes tools/ot303/halfband2x.h with every candidate and prints
# its passband ripple and stopband (from fs/2 - fp, which folds onto fp).
import os
import numpy as np
from scipy import signal

FS = 88200.0
CANDS1 = [(12, 22050.0), (10, 20000.0), (8, 18000.0)]       # first stage, 4x -> 2x (fs 176.4 kHz)
CANDS = [(40, 19000.0), (32, 18000.0), (30, 18000.0), (28, 18000.0), (28, 17000.0), (26, 17000.0), (24, 17000.0),
         (24, 16000.0), (22, 16000.0)]


def design(K, fp, fs=FS):
    g = signal.remez(K, [0, 2 * fp / fs], [1.0], fs=1.0)   # g runs at fs/2: fp maps to 2 fp / fs
    h = np.zeros(2 * K - 1); h[0::2] = g / 2; h[K - 1] = 0.5
    return h


def main():
    out = ['// SPDX-License-Identifier: MIT', '// SPDX-FileCopyrightText: 2026 Zac-Kyoti',
           '// OT-303 second decimator stage (2x -> 1x, fs 88.2 kHz) candidates for the lean engine.',
           '// Generated by tools/ot303/design_halfband2x.py: half-band trick (one-band remez of the odd taps).',
           '#pragma once', 'struct HB2Design { int n, nodd; double fp; const double* odd; };']
    names = []
    f = np.linspace(0, FS / 2, 1 << 15)
    for K, fp in CANDS:
        h = design(K, fp)
        z = np.delete(h[1::2], (K - 1) // 2)                       # every odd index but the centre
        assert abs(h[K - 1] - 0.5) < 1e-15 and np.allclose(z, 0) and np.allclose(h, h[::-1])
        _, H = signal.freqz(h, worN=f, fs=FS)
        m = 20 * np.log10(np.abs(H) + 1e-300)
        rip = np.max(np.abs(m[f <= fp]))
        stop = np.max(m[f >= FS / 2 - fp])
        at = lambda hz: m[np.argmin(np.abs(f - hz))]
        print(f'N {2*K-1:3d} ({K:2d} MACs) fp {fp/1e3:4.1f} kHz: ripple {rip:.4f} dB, stop from {(FS/2-fp)/1e3:.1f} kHz '
              f'{stop:7.1f} dB | 16k {at(16000):+.3f} 18k {at(18000):+.3f} 19k {at(19000):+.3f} 20k {at(20000):+.3f} 21k {at(21000):+.2f}')
        nm = f'HB2_{2*K-1}_{int(fp/1000)}'
        names.append((nm, 2 * K - 1, K, fp))
        out.append(f'static const double {nm}[{K}] = {{')
        out += [f'    {float(v)!r},' for v in h[0::2]]
        out.append('};')
    out.append('static const HB2Design HB2_DESIGNS[] = {')
    out += [f'    {{{n}, {k}, {float(fp)!r}, {nm}}},' for nm, n, k, fp in names]
    out.append('};')
    # the first stage (4x -> 2x): what folds into the kept band comes from >= 88.2 - 16 = 72.2 kHz
    f1 = np.linspace(0, 88200.0, 1 << 15); names1 = []
    for K, fp in CANDS1:
        h = design(K, fp, 176400.0)
        _, H = signal.freqz(h, worN=f1, fs=176400.0)
        m = 20 * np.log10(np.abs(H) + 1e-300)
        print(f'stage 1 N {2*K-1:2d} ({K:2d} MACs) fp {fp/1e3:5.2f} kHz: stop from {(88200-fp)/1e3:.1f} kHz '
              f'{np.max(m[f1 >= 88200 - fp]):6.1f} dB, from 72.2 kHz {np.max(m[f1 >= 72200]):6.1f} dB, '
              f'ripple to 20 kHz {np.max(np.abs(m[f1 <= 20000])):.4f} dB')
        nm = f'HB1_{2*K-1}_{int(fp/1000)}'; names1.append((nm, 2 * K - 1, K, fp))
        out.append(f'static const double {nm}[{K}] = {{')
        out += [f'    {float(v)!r},' for v in h[0::2]]
        out.append('};')
    out.append('static const HB2Design HB1_DESIGNS[] = {')
    out += [f'    {{{n}, {k}, {float(fp)!r}, {nm}}},' for nm, n, k, fp in names1]
    out.append('};')
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'halfband2x.h')
    open(p, 'w').write('\n'.join(out) + '\n')
    print('wrote', p)


if __name__ == '__main__':
    main()
